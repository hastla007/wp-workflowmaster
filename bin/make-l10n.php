<?php
/**
 * Builds the compiled translations from languages/workflow-captain-<locale>.po (SET-WC-06, decision S4):
 * a .mo file for every WordPress version and a .l10n.php file (WordPress 6.5+, read faster).
 *
 *   php bin/make-l10n.php           write languages/workflow-captain-<locale>.mo and .l10n.php
 *   php bin/make-l10n.php --check   exit 1 if a .po misses or has extra strings against the .pot, has an empty
 *                                   translation, or a compiled file is not up to date
 *
 * Locales: de_DE (du) and de_DE_formal (Sie). No mixing of du and Sie in one file (checked by tests/run.php).
 *
 * @package WorkflowCaptain
 */

$root    = dirname( __DIR__ );
$check   = in_array( '--check', $argv, true );
$locales = array( 'de_DE', 'de_DE_formal' );

/**
 * Reads a .po or .pot file: list of entries with ctx, id, plural, str (list of msgstr[n] or one msgstr).
 *
 * @return array<int,array{ctx:?string,id:string,plural:?string,str:array<int,string>}>
 */
function wfc_l10n_read( string $file ): array {
	$entries = array();
	$cur     = null;
	$field   = null;
	$push    = static function () use ( &$cur, &$entries ): void {
		if ( null !== $cur && '' !== $cur['id'] ) {
			$entries[] = $cur;
		}
	};
	foreach ( preg_split( '/\R/', (string) file_get_contents( $file ) ) as $line ) {
		if ( '' === trim( $line ) || str_starts_with( $line, '#' ) ) {
			if ( '' === trim( $line ) ) {
				$push();
				$cur = null;
			}
			continue;
		}
		if ( preg_match( '/^(msgctxt|msgid|msgid_plural|msgstr(?:\[(\d+)\])?)\s+(".*")$/', $line, $m ) ) {
			$cur ??= array( 'ctx' => null, 'id' => '', 'plural' => null, 'str' => array() );
			$value = (string) json_decode( $m[3] );
			switch ( $m[1] ) {
				case 'msgctxt':
					$cur['ctx'] = $value;
					$field      = 'ctx';
					break;
				case 'msgid':
					$cur['id'] = $value;
					$field     = 'id';
					break;
				case 'msgid_plural':
					$cur['plural'] = $value;
					$field         = 'plural';
					break;
				default:
					$n                = '' === ( $m[2] ?? '' ) ? 0 : (int) $m[2];
					$cur['str'][ $n ] = $value;
					$field            = 'str' . $n;
			}
			continue;
		}
		if ( null !== $cur && preg_match( '/^(".*")$/', $line, $m ) ) {
			$value = (string) json_decode( $m[1] );
			if ( str_starts_with( (string) $field, 'str' ) ) {
				$cur['str'][ (int) substr( $field, 3 ) ] .= $value;
			} else {
				$cur[ $field ] .= $value;
			}
		}
	}
	$push();
	return $entries;
}

/** Key of an entry as gettext stores it: context EOT id. */
function wfc_l10n_key( array $e ): string {
	return ( null !== $e['ctx'] ? $e['ctx'] . "\4" : '' ) . $e['id'];
}

/** Binary .mo (little endian, no hash table). */
function wfc_l10n_mo( array $entries, string $plural_forms ): string {
	$map = array( '' => "Content-Type: text/plain; charset=UTF-8\nPlural-Forms: {$plural_forms}\n" );
	foreach ( $entries as $e ) {
		$key         = wfc_l10n_key( $e ) . ( null !== $e['plural'] ? "\0" . $e['plural'] : '' );
		$map[ $key ] = implode( "\0", $e['str'] );
	}
	ksort( $map, SORT_STRING );
	$n       = count( $map );
	$ids     = '';
	$strs    = '';
	$id_tab  = array();
	$str_tab = array();
	$offset  = 28 + 16 * $n;
	foreach ( $map as $id => $str ) {
		$id_tab[] = array( strlen( (string) $id ), strlen( $ids ) );
		$ids     .= $id . "\0";
	}
	$str_start = $offset + strlen( $ids );
	foreach ( $map as $str ) {
		$str_tab[] = array( strlen( $str ), strlen( $strs ) );
		$strs     .= $str . "\0";
	}
	$out = pack( 'V7', 0x950412de, 0, $n, 28, 28 + 8 * $n, 0, 0 );
	foreach ( $id_tab as list( $len, $pos ) ) {
		$out .= pack( 'V2', $len, $offset + $pos );
	}
	foreach ( $str_tab as list( $len, $pos ) ) {
		$out .= pack( 'V2', $len, $str_start + $pos );
	}
	return $out . $ids . $strs;
}

/** PHP translation file (WordPress 6.5+). */
function wfc_l10n_php( array $entries, string $locale, string $plural_forms ): string {
	$messages = array();
	foreach ( $entries as $e ) {
		$messages[ wfc_l10n_key( $e ) ] = implode( "\0", $e['str'] );
	}
	ksort( $messages, SORT_STRING );
	$data = array(
		'domain'        => 'workflow-captain',
		'plural-forms'  => $plural_forms,
		'language'      => $locale,
		'messages'      => $messages,
	);
	return "<?php\n// Generated by bin/make-l10n.php from languages/workflow-captain-{$locale}.po. Do not edit.\nreturn " . var_export( $data, true ) . ";\n";
}

$pot      = wfc_l10n_read( $root . '/languages/workflow-captain.pot' );
$pot_keys = array_map( 'wfc_l10n_key', $pot );
$errors   = array();
foreach ( $locales as $locale ) {
	$po_file = $root . "/languages/workflow-captain-{$locale}.po";
	if ( ! is_readable( $po_file ) ) {
		$errors[] = "{$locale}: .po missing";
		continue;
	}
	$po      = wfc_l10n_read( $po_file );
	$keys    = array_map( 'wfc_l10n_key', $po );
	$missing = array_diff( $pot_keys, $keys );
	$extra   = array_diff( $keys, $pot_keys );
	foreach ( $missing as $k ) {
		$errors[] = "{$locale}: not translated: {$k}";
	}
	foreach ( $extra as $k ) {
		$errors[] = "{$locale}: no longer used: {$k}";
	}
	foreach ( $po as $e ) {
		if ( array() === $e['str'] || in_array( '', $e['str'], true ) ) {
			$errors[] = "{$locale}: empty translation: {$e['id']}";
		}
	}
	$plural_forms = 'nplurals=2; plural=(n != 1);';
	$mo           = wfc_l10n_mo( $po, $plural_forms );
	$php          = wfc_l10n_php( $po, $locale, $plural_forms );
	$targets      = array(
		$root . "/languages/workflow-captain-{$locale}.mo"        => $mo,
		$root . "/languages/workflow-captain-{$locale}.l10n.php" => $php,
	);
	foreach ( $targets as $file => $content ) {
		if ( $check ) {
			if ( ! is_readable( $file ) || file_get_contents( $file ) !== $content ) {
				$errors[] = "{$locale}: " . basename( $file ) . ' is not up to date; run php bin/make-l10n.php';
			}
		} else {
			file_put_contents( $file, $content );
		}
	}
	if ( ! $check ) {
		echo "Wrote {$locale}: " . count( $po ) . " strings\n";
	}
}
if ( array() !== $errors ) {
	fwrite( STDERR, implode( "\n", array_slice( $errors, 0, 40 ) ) . "\n" . count( $errors ) . " problem(s)\n" );
	exit( 1 );
}
if ( $check ) {
	echo 'Translations up to date: ' . implode( ', ', $locales ) . "\n";
}
